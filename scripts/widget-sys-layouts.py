#!/usr/bin/env python3
"""The widgets' layouts for a device with a font chosen in its display settings: the same layouts without the widgets'
own font (Noto Sans Hebrew for the Hebrew), so every letter is drawn in the device's font. Run after changing
widget_clock.xml, widget_row.xml or widget_row_live.xml; WidgetRenderTest fails while a copy is out of date."""
import os, re
D = os.path.join(os.path.dirname(__file__), '..', 'android', 'app', 'src', 'main', 'res', 'layout')
DIGITS = ['k_time', 'k_sec', 'k_greg', 'k_wt', 'k_dd', 'k_hh', 'k_mm', 'k_ss', 'k_n1', 'k_n2', 'k_n3', 'k_n4', 'k_n5', 'k_hs',
          'k_as', 'k_lc', 'k_comp_n', 'k_wd_n', 'k_ls_n', 'k_lq_n', 'w_days', 'w_hours', 'w_chrono', 'w_chrono2', 'w_hs', 'w_as',
          'w_clock', 'w_comp_n', 'w_when_n', 'w_q_n']
for n in ['widget_clock', 'widget_row', 'widget_row_live']:
    s = open(os.path.join(D, n + '.xml'), encoding='utf-8').read()
    s = s.replace(' android:fontFamily="@font/noto_sans_hebrew"', '')
    # the device's font may have digits of different widths: its numbers ask for tabular digits (Noto's are tabular
    # already and it has no such feature, so the Noto layouts do not ask for it)
    for i in DIGITS:
        s = re.sub(r'(<(?:TextView|TextClock|Chronometer) [^>]*android:id="@\+id/' + i + r'")', r'\1 android:fontFeatureSettings="tnum"', s)
    s = re.sub(r'^(<\?xml[^>]*>\n)', r'\1<!-- GENERATED by scripts/widget-sys-layouts.py from ' + n + '.xml: the same layout in the device\'s font. Do not edit. -->\n', s, count=1)
    open(os.path.join(D, n + '_sys.xml'), 'w', encoding='utf-8').write(s)
    print(n + '_sys.xml')
